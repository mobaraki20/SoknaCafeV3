<?php
declare(strict_types=1);
require __DIR__.'/../forward-foodcost/local/src/Domain/Reporting/CatalogFoodCost.php';
use Sokna\Local\Domain\Reporting\CatalogFoodCost;
$n=0;
$ok=function(bool $condition,string $label)use(&$n):void{$n++;if(!$condition)throw new RuntimeException($label);};
$recipe=['completeness_status'=>'complete','review_status'=>'ready'];
$c=['inventory_item_id'=>1,'inventory_item_name'=>'بستنی','quantity_base'=>100,'average_unit_cost'=>'25.500000','cost_status'=>'known','quantity_status'=>'known','base_unit'=>'g','cost_updated_at'=>'2026-11-01 01:00:00'];
$r=CatalogFoodCost::estimate([$c],$recipe,8500);
$ok($r['ingredient_cost']===2550,'100g * base-gram-cost');
$ok($r['food_cost_percent']===30.0,'percent');
$ok($r['price_minus_ingredients']===5950,'price difference');
$ok($r['status']==='known','known');
$r=CatalogFoodCost::estimate([array_replace($c,['average_unit_cost'=>null])],$recipe,8000);
$ok($r['ingredient_cost']===null,'missing cost not zero');
$ok($r['known_cost_subtotal']===0,'known subtotal is not total');
$ok($r['status']==='partial','partial when cost missing');
$r=CatalogFoodCost::estimate([$c],['completeness_status'=>'partial','review_status'=>'ready'],8000);
$ok($r['ingredient_cost']===null,'incomplete recipe not total');
$r=CatalogFoodCost::estimate([array_replace($c,['cost_status'=>'estimated'])],$recipe,8000);
$ok($r['status']==='estimated','estimated provenance');
$r=CatalogFoodCost::estimate([array_replace($c,['quantity_status'=>'estimated'])],$recipe,8000);
$ok($r['status']==='estimated','estimated quantity');
$r=CatalogFoodCost::estimate([],null,8000);
$ok($r['status']==='missing_recipe','absent recipe');
$r=CatalogFoodCost::estimate([$c],$recipe,8000,true);
$ok($r['ingredient_cost']===null&&$r['status']==='bundle_needs_review','bundle not double counted');
$r=CatalogFoodCost::estimate([$c],$recipe,0);
$ok($r['food_cost_percent']===null,'zero sale price no percent');
$ok($r['ingredient_cost']===2550,'zero sale price cost still known');
$ok($r['components'][0]['line_cost']===2550,'line calculation');
$ok($r['oldest_cost_updated_at']==='2026-11-01 01:00:00','cost basis');
$ok(CatalogFoodCost::estimate([array_replace($c,['cost_status'=>'partial'])],$recipe,9000)['ingredient_cost']===null,'partial cost excluded');
$ok(CatalogFoodCost::estimate([$c,array_replace($c,['inventory_item_id'=>2,'average_unit_cost'=>'1.25','quantity_base'=>10])],$recipe,9000)['ingredient_cost']===2563,'multiple ingredient rounding once');
echo "PASS {$n} calculator assertions\n";
