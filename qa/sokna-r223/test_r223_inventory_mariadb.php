<?php
declare(strict_types=1);
// QA ONLY: explicit ephemeral GitHub Actions MariaDB that R222 fixture initialized.
if(getenv('GITHUB_ACTIONS')!=='true'||getenv('SOKNA_R212_DISPOSABLE_ONLY')!=='YES')throw new RuntimeException('R223_DISPOSABLE_CI_ONLY');
$web=(string)getenv('SOKNA_R212_WEB');$root=realpath((string)getenv('RUNNER_TEMP'));
if(!$root||!is_file($web.'/bootstrap.php')||!str_starts_with((string)realpath($web),$root.DIRECTORY_SEPARATOR))throw new RuntimeException('R223_NON_TEMP_REFUSED');
require_once $web.'/bootstrap.php';
$pdo=new PDO('mysql:host=127.0.0.1;port=3306;dbname=sokna_r212_disposable;charset=utf8mb4','root',(string)getenv('SOKNA_R212_DB_PASSWORD'),[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION,PDO::ATTR_EMULATE_PREPARES=>false]);
$pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE,PDO::FETCH_ASSOC);
if((int)$pdo->query('SELECT COUNT(*) FROM schema_migrations')->fetchColumn()!==81)throw new RuntimeException('R223_MIGRATIONS_81_REQUIRED');
$uid=(int)$pdo->query("SELECT id FROM users WHERE role='admin' AND active=1 ORDER BY id LIMIT 1")->fetchColumn();
if($uid<1)throw new RuntimeException('R223_ADMIN_REQUIRED');
$idRepo=new \Sokna\Local\Core\PdoIdentityRepository($pdo);
$inventory=new \Sokna\Local\Domain\Inventory\InventoryService($pdo,$idRepo,new \Sokna\Local\Core\Capabilities($idRepo));
$orders=new \Sokna\Local\Domain\Inventory\InventoryOrderService($pdo,$inventory);
$testCount=0;
$ok=static function(bool $cond,string $label)use(&$testCount):void{if(!$cond)throw new RuntimeException('FAIL_R223_'.$label);$testCount++;echo 'PASS_R223_'.$label."\n";};
$get=static function(string $sql,array $args=[])use($pdo){$s=$pdo->prepare($sql);$s->execute($args);return $s->fetchColumn();};
$rows=static function(string $sql,array $args=[])use($pdo):array{$s=$pdo->prepare($sql);$s->execute($args);return $s->fetchAll(PDO::FETCH_ASSOC)?:[];};
$pdo->prepare("UPDATE settings SET setting_value='1' WHERE setting_key='inventory_initialized'")->execute();
$ok((string)$get("SELECT setting_value FROM settings WHERE setting_key='inventory_initialized'")==='1','EPHEMERAL_INVENTORY_READY');
$order=$rows("SELECT o.id order_id,oi.id order_item_id,oi.item_id parent_item_id,oi.ordered_quantity FROM orders o JOIN order_items oi ON oi.order_id=o.id WHERE oi.item_name='R222 bundle parent' ORDER BY o.id DESC LIMIT 1");
if(count($order)!==1)throw new RuntimeException('R223_R222_FIXTURE_ORDER_REQUIRED');
$orderId=(int)$order[0]['order_id'];$oi=(int)$order[0]['order_item_id'];$parent=(int)$order[0]['parent_item_id'];
$componentRows=$rows('SELECT component_item_id,component_mode,quantity FROM order_item_bundle_components WHERE order_item_id=? ORDER BY id',[$oi]);
$ok(count($componentRows)===2,'REAL_TWO_BUNDLE_COMPONENTS');
$fixed=(int)$componentRows[0]['component_item_id'];$choice=(int)$componentRows[1]['component_item_id'];
$ok($fixed!==$choice && (int)$componentRows[0]['quantity']===4 && (int)$componentRows[1]['quantity']===2,'REAL_FIXED_CHOICE_RATIO_2_V_1');
$inv=(int)$get('SELECT c.inventory_item_id FROM inventory_recipe_versions v JOIN inventory_recipe_components c ON c.recipe_version_id=v.id WHERE v.status=\'active\' AND v.menu_item_id=? ORDER BY c.id LIMIT 1',[$fixed]);
$ok($inv>0,'REAL_INVENTORY_INGREDIENT_FOUND');
$balance=static function()use($get,$inv):int{return (int)$get('SELECT quantity_base FROM inventory_balances WHERE inventory_item_id=?',[$inv]);};
$movement=static function(string|int $itemId,string $source)use($rows):array{return $rows('SELECT id,quantity_base,unit_cost_snapshot,total_cost_delta,cost_status,idempotency_key FROM inventory_movements WHERE source_type=? AND source_id=? ORDER BY id',[$source,$itemId]);};
$start=$balance();
$ok($start===100000,'FIXTURE_INITIAL_BALANCE_100000');
$pdo->beginTransaction();
$snap=$orders->orderRecipeSnapshotTx($orderId);
$ok(count($snap)===2,'ACCOUNTED_SNAPSHOT_TWO_ROWS');
$units=array_map(static fn(array $x)=>[$x['bundle_units_per_parent']??null,$x['parent_order_quantity']??null],$snap);
$ok($units===[[2,2],[1,2]],'ACCOUNTED_SNAPSHOT_FROZEN_BUNDLE_MULTIPLIERS');
$summary=$orders->costSummaryFromRecipeSnapshot($snap);
$ok((int)$summary['known_cost_amount']===144,'HISTORICAL_ACCOUNTED_COST_144');
$eventId=$orders->enqueueAccountedTx($orderId,$uid);
$ok(is_int($eventId)&&$eventId>0,'ACCOUNTED_EVENT_CREATED');
$pdo->commit();
$ok((string)$get('SELECT status FROM inventory_order_events WHERE id=?',[$eventId])==='done','ACCOUNTED_APPLIED');
$accountMovements=$movement($oi,'order_item');
$ok(count($accountMovements)===2,'TWO_COMPONENT_MOVEMENTS_APPLIED');
$ok(array_map(static fn(array $x)=>(int)$x['quantity_base'],$accountMovements)===[-40,-8],'MATERIAL_DEBIT_40_PLUS_8');
$ok($balance()===$start-48,'BALANCE_AFTER_ACCOUNTED');
$ok(array_reduce($accountMovements,static fn(int $a,array $m)=>$a+(int)$m['total_cost_delta'],0)===-144,'REAL_DEBIT_COST_144');
$pdo->beginTransaction();$secondEventId=$orders->enqueueAccountedTx($orderId,$uid);$pdo->commit();
$ok($secondEventId===$eventId && count($movement($oi,'order_item'))===2 && $balance()===$start-48,'RETRY_ACCOUNTED_EXACTLY_ONCE');
// Subsequent changes in the current purchasing average must NOT reprice historical movements.
$pdo->prepare('UPDATE inventory_balances SET average_unit_cost=9.000000 WHERE inventory_item_id=?')->execute([$inv]);
$pdo->beginTransaction();
$adjustId=$orders->enqueueQuantityAdjustedTx($orderId,$oi,2,3,1,$uid,'r223-main-one');
$ok(is_int($adjustId)&&$adjustId>0,'BUNDLE_ADJUST_EVENT_CREATED');
$pdo->commit();
$ok((string)$get('SELECT status FROM inventory_order_events WHERE id=?',[$adjustId])==='done','BUNDLE_ADJUST_EVENT_APPLIED');
$adjustments=$movement('r223-main-one','order_item_adjustment');
$ok(count($adjustments)===2,'BUNDLE_ADJUSTS_ALL_COMPONENTS');
$ok(array_map(static fn(array $x)=>(int)$x['quantity_base'],$adjustments)===[-20,-4],'BUNDLE_ADJUSTS_WITH_CHILD_MULTIPLIERS');
$ok($balance()===$start-72,'BALANCE_AFTER_PLUS_ONE_BUNDLE');
$ok(array_reduce($adjustments,static fn(int $a,array $m)=>$a+(int)$m['total_cost_delta'],0)===-72,'ADJUSTMENT_PRESERVES_ORIGINAL_COST_NOT_NEW_AVG');
$ok(array_reduce($adjustments,static fn(bool $a,array $m)=>$a&&abs((float)$m['unit_cost_snapshot']-3.0)<0.000001,true),'ORIGINAL_UNIT_COST_FROZEN');
$pdo->beginTransaction();$duplicateAdjust=$orders->enqueueQuantityAdjustedTx($orderId,$oi,2,3,1,$uid,'r223-main-one');$pdo->commit();
$ok($duplicateAdjust===$adjustId && count($movement('r223-main-one','order_item_adjustment'))===2 && $balance()===$start-72,'RETRY_ADJUSTMENT_EXACTLY_ONCE');
// A real bundle may offer the SAME sellable as both fixed and selected child.
// The recipe_component_id is identical across two snapshots: old idempotency keys collapse these into one movement.
$tableId=(int)$get('SELECT table_id FROM orders WHERE id=?',[$orderId]);
$token='r223-repeat-'.bin2hex(random_bytes(8));
$publicCode='R223'.bin2hex(random_bytes(6));
$businessNumber=(int)$get('SELECT COALESCE(MAX(business_order_number),0)+1 FROM orders WHERE business_date=CURDATE()');
$pdo->prepare("INSERT INTO orders(public_code,client_token,table_id,order_source,status,total_amount,business_order_number,business_date,business_shift_key,business_shift_label,business_cutoff_snapshot) VALUES(?,?,?,'guest','accounted',37000,?,CURDATE(),'r223','R223 QA','04:00')")
    ->execute([$publicCode,$token,$tableId,$businessNumber]);
$repeatOrderId=(int)$pdo->lastInsertId();
$pdo->prepare("INSERT INTO order_items(order_id,item_id,item_name,unit_price,quantity,ordered_quantity,preparation_station,line_total) VALUES(?,?,?,37000,1,1,'kitchen',37000)")
    ->execute([$repeatOrderId,$parent,'R223 bundle repeated']);
$repeatOi=(int)$pdo->lastInsertId();
$cinsert=$pdo->prepare('INSERT INTO order_item_bundle_components(order_item_id,component_item_id,item_name_snapshot,quantity,preparation_station_snapshot,component_mode) VALUES(?,?,?,?,?,?)');
$cinsert->execute([$repeatOi,$fixed,'R223 fixed',2,'kitchen','fixed']);
$cinsert->execute([$repeatOi,$fixed,'R223 selected',1,'kitchen','choice']);
$beforeRepeat=$balance();
$pdo->beginTransaction();
$repeatedSnapshot=$orders->orderRecipeSnapshotTx($repeatOrderId);
$ok(count($repeatedSnapshot)===2 && (int)$repeatedSnapshot[0]['recipe_version_id']===(int)$repeatedSnapshot[1]['recipe_version_id'],'REPEATED_RECIPE_COMPONENT_EXACT_SAME_VERSION');
$repeatEvt=$orders->enqueueAccountedTx($repeatOrderId,$uid);$pdo->commit();
$ok($repeatEvt>0 && (string)$get('SELECT status FROM inventory_order_events WHERE id=?',[$repeatEvt])==='done','REPEATED_COMPONENT_ACCOUNTED_EVENT_DONE');
$repeatedMovements=$movement($repeatOi,'order_item');
$ok(count($repeatedMovements)===2 && (int)$repeatedMovements[0]['quantity_base']===-20 && (int)$repeatedMovements[1]['quantity_base']===-10,'REPEATED_COMPONENT_HAS_TWO_DISTINCT_MOVEMENTS');
$ok($balance()===$beforeRepeat-30,'REPEATED_COMPONENT_FULL_30_DEBIT');
$ok(str_contains((string)$repeatedMovements[1]['idempotency_key'],':repeat:2'),'REPEATED_COMPONENT_SECOND_KEY_DISTINCT');
$pdo->beginTransaction();$repeatAdjustId=$orders->enqueueQuantityAdjustedTx($repeatOrderId,$repeatOi,1,2,1,$uid,'r223-repeat-adj');$pdo->commit();
$repeatedAdjustments=$movement('r223-repeat-adj','order_item_adjustment');
$ok($repeatAdjustId>0 && count($repeatedAdjustments)===2,'REPEATED_COMPONENT_ADJUST_EVENT_TWO_MOVEMENTS');
$ok(array_map(static fn(array $x)=>(int)$x['quantity_base'],$repeatedAdjustments)===[-20,-10],'REPEATED_COMPONENT_ADJUST_INCLUDES_EACH_OCCURRENCE');
$ok($balance()===$beforeRepeat-60,'REPEATED_COMPONENT_BALANCE_AFTER_ADJUST');
// Negative adjustments reverse the correct quantity using the original recipe snapshot.
$pdo->beginTransaction();$revertId=$orders->enqueueQuantityAdjustedTx($repeatOrderId,$repeatOi,2,1,-1,$uid,'r223-repeat-revert');$pdo->commit();
$reversals=$movement('r223-repeat-revert','order_item_adjustment');
$ok($revertId>0&&count($reversals)===2&&array_map(static fn(array $x)=>(int)$x['quantity_base'],$reversals)===[20,10],'REVERSES_ALL_FIXED_AND_SELECTED_COMPONENTS');
$ok($balance()===$beforeRepeat-30,'REVERSED_BALANCE_EXACT');
$ok((int)$get("SELECT COUNT(*) FROM inventory_order_events WHERE order_id IN (?,?) AND status<>'done'",[$orderId,$repeatOrderId])===0,'ALL_OWN_EVENTS_FINISHED');
echo 'PASS_R223_REAL_MARIADB_'.$testCount."_CHECKS\n";