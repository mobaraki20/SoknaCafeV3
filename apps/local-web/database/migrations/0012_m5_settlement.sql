    ADD COLUMN discount_type VARCHAR(20) NULL,
    ADD COLUMN discount_value BIGINT UNSIGNED NOT NULL DEFAULT 0,
    ADD COLUMN discount_amount BIGINT UNSIGNED NOT NULL DEFAULT 0,
    ADD COLUMN discount_by_user_id INT UNSIGNED NULL,
    ADD COLUMN discount_updated_at DATETIME NULL,
    ADD COLUMN checkout_subtotal BIGINT UNSIGNED NULL,
    ADD COLUMN checkout_discount BIGINT UNSIGNED NULL,
    ADD COLUMN checkout_total BIGINT UNSIGNED NULL,
    ADD COLUMN settlement_destination VARCHAR(30) NULL,
    ADD COLUMN checkout_voided_at DATETIME NULL,
    ADD COLUMN checkout_voided_by_user_id INT UNSIGNED NULL,
    ADD COLUMN closed_by_user_id INT UNSIGNED NULL,
