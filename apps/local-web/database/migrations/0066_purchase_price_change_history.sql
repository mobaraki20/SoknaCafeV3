-- INV-PURCHASE-PRICE-CHANGE-01: immutable purchase price comparison snapshots + configurable notification policy.
CREATE TABLE IF NOT EXISTS inventory_purchase_price_events (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    receipt_id BIGINT UNSIGNED NOT NULL,
    inventory_item_id INT UNSIGNED NOT NULL,
    item_name_snapshot VARCHAR(180) NOT NULL,
    category_key_snapshot VARCHAR(64) NOT NULL,
    category_name_snapshot VARCHAR(140) NOT NULL,
    movement_id BIGINT UNSIGNED NOT NULL,
    supplier VARCHAR(160) NULL,
    purchase_unit_id INT UNSIGNED NULL,
    purchase_unit_name_snapshot VARCHAR(120) NULL,
    purchase_unit_count DECIMAL(14,3) NULL,
    base_unit ENUM('g','ml','count') NOT NULL,
    received_quantity_base BIGINT NOT NULL,
    raw_total_cost BIGINT NOT NULL,
    normalized_unit_cost DECIMAL(18,6) NOT NULL,
    last_receipt_id BIGINT UNSIGNED NULL,
    last_movement_id BIGINT UNSIGNED NULL,
    last_unit_cost DECIMAL(18,6) NULL,
    last_purchase_at DATETIME NULL,
    weighted_average_before DECIMAL(18,6) NULL,
    weighted_average_after DECIMAL(18,6) NULL,
    delta_last_amount DECIMAL(18,6) NULL,
    delta_last_percent DECIMAL(12,4) NULL,
    delta_average_amount DECIMAL(18,6) NULL,
    delta_average_percent DECIMAL(12,4) NULL,
    impact_vs_last BIGINT NULL,
    impact_vs_average BIGINT NULL,
    direction ENUM('increase','decrease','unchanged','baseline') NOT NULL DEFAULT 'baseline',
    comparison_status VARCHAR(40) NOT NULL,
    notification_level ENUM('history_only','standard','high') NOT NULL DEFAULT 'history_only',
    purchase_occurred_at DATETIME NOT NULL,
    actor_user_id INT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_inv_purchase_price_receipt(receipt_id),
    INDEX idx_inv_purchase_price_item_time(inventory_item_id,purchase_occurred_at,id),
    INDEX idx_inv_purchase_price_category_time(category_key_snapshot,purchase_occurred_at,id),
    INDEX idx_inv_purchase_price_direction_time(direction,purchase_occurred_at,id),
    INDEX idx_inv_purchase_price_supplier_time(supplier,purchase_occurred_at,id),
    CONSTRAINT fk_inv_purchase_price_receipt FOREIGN KEY(receipt_id) REFERENCES inventory_supply_receipts(id),
    CONSTRAINT fk_inv_purchase_price_item FOREIGN KEY(inventory_item_id) REFERENCES inventory_items(id),
    CONSTRAINT fk_inv_purchase_price_movement FOREIGN KEY(movement_id) REFERENCES inventory_movements(id),
    CONSTRAINT fk_inv_purchase_price_last_receipt FOREIGN KEY(last_receipt_id) REFERENCES inventory_supply_receipts(id),
    CONSTRAINT fk_inv_purchase_price_actor FOREIGN KEY(actor_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO settings(setting_key,setting_value) VALUES
('inventory.purchase_price_notifications.enabled','0')
ON DUPLICATE KEY UPDATE setting_key=VALUES(setting_key);
